def generate_package_files(
    plans: list[ScenarioPlan],
    *,
    source_name: str,
    package_name: str | None = None,
    description: str | None = None,
) -> dict[str, str]:
    """Render a full scenario package as ``{relative_path: file_content}``.

    Args:
        plans: The transpiled scenario variants (one per ``one_of`` branch).
        source_name: The originating ``.osc`` path (recorded in docstrings).
        package_name: Desired package name; defaults to ``<scenario>_package``.
        description: Optional package description.

    Returns:
        A mapping of package-relative file paths to their contents.
    """
    if not plans:
        raise ValueError("generate_package_files requires at least one plan")

    # Imported lazily: pulls in jinja2 via the scaffold module, which the rest
    # of the frontend does not need.
    from ..scaffold.generator import resolve_names

    base_dsl_name = plans[0].name.split(".")[-1]
    raw_name = package_name or f"{base_dsl_name}_package"
    names = resolve_names(raw_name, description=description)
    pkg = names["package_name"]
    base_scenario = names["scenario_name"]
    base_class = names["scenario_class"]
    config_class = names["config_class"]
    description = names["description"]

    # Work on copies so injected timeouts don't leak into the caller's plans.
    plans = [replace(p, specs=list(p.specs)) for p in plans]
    timeout = _default_timeout(plans)
    for plan in plans:
        _ensure_timeout(plan, timeout)

    count = len(plans)
    variant_scn: list[str] = []
    variant_cls: list[str] = []
    for i in range(count):
        scn, cls = _variant_names(base_scenario, base_class, i, count)
        variant_scn.append(scn)
        variant_cls.append(cls)

    scenario_module = _render_scenario_module(
        plans,
        source_name=source_name,
        class_names=variant_cls,
        config_class=config_class,
    )

    files: dict[str, str] = {
        "pyproject.toml": _render_pyproject(
            names["distribution_name"], pkg, description
        ),
        "README.md": _render_readme(
            names["distribution_name"], variant_scn, source_name, plans
        ),
        f"src/{pkg}/__init__.py": _render_init(
            pkg,
            base_scenario,
            config_class,
            description,
            list(zip(variant_scn, variant_cls)),
        ),
        f"src/{pkg}/{base_scenario}.py": scenario_module,
        f"src/{pkg}/configs.py": _render_configs(config_class, base_scenario, timeout),
    }
    for plan, scn in zip(plans, variant_scn):
        files[f"src/{pkg}/conf/scenario/{scn}/default.yaml"] = _render_default_yaml(
            plan, scn, timeout
        )
    return files
