"""Render transpiled scenarios as a standalone *scenario package*.

Instead of a single self-contained module (see :mod:`.codegen`), this produces
the installable package layout introduced in ``autoware_carla_scenario`` — a
``pyproject.toml`` with an ``autoware_carla_scenario.scenarios`` entry point,
``src/<pkg>/{__init__,configs,<scenario>}.py`` and per-variant Hydra configs:

    <package>/
        pyproject.toml
        README.md
        src/<package>/
            __init__.py                              # register() hooks
            <scenario>.py                            # transpiled BaseScenario(s)
            configs.py                               # config dataclass
            conf/scenario/<variant>/default.yaml     # concrete values

Each ``one_of`` variant becomes a separately registered scenario, so the package
plugs straight into the framework's ``uv run scenario`` / multirun flow.
"""

from __future__ import annotations

from dataclasses import replace

from .codegen import _INDENT, _Emitter, _indent, _setup_body
from .plan import ScenarioPlan, Spec, SpecKind

#: Default fail-safe timeout (seconds) when the DSL declares none.
_DEFAULT_TIMEOUT_SECONDS = 60.0


def _variant_names(base_scenario: str, base_class: str, index: int, count: int):
    if count == 1:
        return base_scenario, base_class
    return f"{base_scenario}_v{index}", f"{base_class}V{index}"


def _default_timeout(plans: list[ScenarioPlan]) -> float:
    for plan in plans:
        for spec in plan.specs:
            if spec.kind is SpecKind.TIMEOUT:
                return float(spec.params["seconds"])
    return _DEFAULT_TIMEOUT_SECONDS


def _ensure_timeout(plan: ScenarioPlan, seconds: float) -> None:
    """Guarantee a config-driven timeout fail-condition exists on *plan*."""
    if not any(s.kind is SpecKind.TIMEOUT for s in plan.specs):
        plan.specs.append(
            Spec(
                kind=SpecKind.TIMEOUT,
                actor=plan.ego.name,
                label="scenario_timeout",
                params={"seconds": seconds},
            )
        )


